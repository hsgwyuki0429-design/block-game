  separation: 2,
  /** 引き離しに使ってよい手の上限 */
  separationPushes: 30,
  /** 引き離し1手あたりに評価する巻き戻し候補の数 */
  separationTries: 40,
  /** 巻き戻しで「相棒から離れること」をどれだけ重く見るか */
  gapWeight: 9,
